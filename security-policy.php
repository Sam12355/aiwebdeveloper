<p class="note">This Security Policy explains how <strong>Web Designer &amp; Web Developer (Pvt) Ltd</strong> protects ecommercesrilanka.lk, customer data, admin access, uploaded files, and project records.</p>
<h2>1. Security Approach</h2>
<p>We apply layered security controls across website forms, admin workflows, file uploads, backend APIs, database records, and cPanel hosting configuration. The goal is to reduce unauthorized access, spam, injection attacks, malicious uploads, data leakage, and misuse of the platform.</p>
<h2>2. Website and Server Protection</h2>
<ul><li>Security headers are added through server configuration where supported.</li><li>Directory listing is disabled.</li><li>Sensitive backend folders and upload areas are restricted.</li><li>PHP execution inside upload folders is blocked.</li><li>SQL and configuration files are protected from public browsing where supported by the server.</li></ul>
<h2>3. Admin and Data Protection</h2>
<p>Admin dashboard access, project records, payment receipts, template management, package management, customer communication, and realtime notifications must be handled only by authorized persons. Production deployment should use secure login, strong passwords, HTTPS, and database credentials stored in protected configuration files.</p>
<h2>4. File Upload Security</h2>
<p>Payment slips, logos, and additional files must be validated by file type and size. Executable files, unsafe scripts, unknown binary files, and suspicious uploads should be rejected. Upload folders should not allow PHP or executable code to run.</p>
<h2>5. Copyright, Trademark, and Concept Protection</h2>
<p>The complete platform concept, AI website-building flow, admin management system, business method presentation, interface structure, template management concept, written content, brand marks, and software logic are owned by <strong>Web Designer &amp; Web Developer (Pvt) Ltd</strong>. These assets are protected under Sri Lankan law and applicable international intellectual property and trademark principles.</p>
<h2>6. Incident Handling</h2>
<p>If a security issue is suspected, access should be reviewed immediately, affected credentials changed, suspicious files removed, backups checked, server logs reviewed, and the hosting provider contacted when required.</p>
<h2>7. Disclaimer</h2>
<p>We take strong security measures, but no website, server, plugin, API, email, SMS, or payment system can be guaranteed completely free from risk. Clients must also protect their own passwords, devices, email accounts, payment credentials, and business data.</p>
